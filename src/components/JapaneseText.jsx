const readings = new Map(vocabulary.map(entry => {
  const surface = entry.replace(/\[[ぁ-ゖ]+\]/gu, '')
  const parts = Array.from(entry.matchAll(/([\p{Script=Han}々]+)\[([ぁ-ゖ]+)\]|([ぁ-ゖ]+)/gu),
    ([, kanji, kana, plain]) => kanji ? { kanji, kana } : plain)
  return [surface, parts]
}))

// All surfaces are Japanese letters. Prefer the whole compound, e.g. 整理整頓 over 整理.
const words = [...readings.keys()].sort((a, b) => b.length - a.length)
const matcher = new RegExp('(' + words.join('|') + ')', 'gu')

export default function JapaneseText({ children }) {
  return (
    <span lang="ja" className="japanese-text">
      {children.split(matcher).map((word, index) => {
        const parts = readings.get(word)
        if (!parts) return word
        return parts.map((part, offset) => typeof part === 'string' ? part : (
          <ruby key={index + '-' + offset}>{part.kanji}<rt>{part.kana}</rt></ruby>
        ))
      })}
    </span>
  )
}
